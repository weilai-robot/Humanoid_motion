#!/usr/bin/env python3
"""Export the v11 leg geometry for the dependency-free body state estimator."""
import argparse
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET


def export(source: Path, output: Path):
    root = ET.parse(source).getroot()
    rows, names, feet = [], [], []
    for side in ("left", "right"):
        leg, leg_names = [], []
        for suffix in ("hip_pitch", "hip_roll", "hip_yaw", "knee_pitch", "ankle_pitch", "ankle_roll"):
            body = root.find(f".//body[@name='{side}_{suffix}_link']")
            joint, inertia = body.find("joint"), body.find("inertial")
            assert joint.get("pos", "0 0 0") == "0 0 0"
            assert body.get("euler") is None
            values = [body.get("pos", "0 0 0"), body.get("quat", "1 0 0 0"),
                      joint.get("axis"), inertia.get("pos"), inertia.get("mass")]
            leg.append("    {" + ", ".join("{" + ", ".join(v.split()) + "}" for v in values[:-1]) + ", " + values[-1] + "}")
            leg_names.append('"' + joint.get("name") + '"')
        spheres = [g for g in body.findall("geom") if g.get("class") == "collision" and g.get("type") == "sphere"]
        assert len(spheres) == 4
        feet.append("  {{" + ", ".join("{{" + ", ".join(g.get("pos").split()) + "}, " + g.get("size") + "}" for g in spheres) + "}}")
        rows.append("  {{\n" + ",\n".join(leg) + "\n  }}")
        names += leg_names
    header = '''#pragma once
// Generated by tools/export_x1_leg_kinematics.py. Model coordinates; no hardware signs.
// Training MJCF SHA256: SOURCE_HASH
#include "control_module/dance_state_adapter.h"

namespace xyber_x1_infer::rl_control_module {
struct DanceLegLink {
  std::array<double, 3> translation;
  std::array<double, 4> rotation;
  std::array<double, 3> axis;
  std::array<double, 3> com;
  double mass;
};
struct DanceFootPoint { std::array<double, 3> position; double radius; };
inline constexpr std::array<const char*, 12> kDanceLegJointNames{NAMES};
inline constexpr std::array<std::array<DanceLegLink, 6>, 2> kDanceLegLinks{{
ROWS
}};
inline constexpr std::array<std::array<DanceFootPoint, 4>, 2> kDanceFootPoints{{
FEET
}};
}  // namespace xyber_x1_infer::rl_control_module
'''.replace("SOURCE_HASH", hashlib.sha256(source.read_bytes()).hexdigest()).replace("NAMES", ", ".join(names)).replace("ROWS", ",\n".join(rows)).replace("FEET", ",\n".join(feet))
    output.write_text(header)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    export(args.model, args.output)
